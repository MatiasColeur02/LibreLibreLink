import Foundation
import Testing
@testable import LibreKit

private let utc = TimeZone(identifier: "UTC")!

private func date(_ text: String) -> Date {
    try! Date(text + "Z", strategy: .iso8601)
}

@Test func parsesSpanishExport() throws {
    let csv = """
        \u{FEFF}Datos de glucosa,Generado el,12-10-2026 09:00 UTC,Generado por,Matias
        Dispositivo,Número de serie,Sello de tiempo del dispositivo,Tipo de registro,Historial de glucosa mg/dL,Escaneo de glucosa mg/dL,Insulina de acción rápida no numérica,Insulina de acción rápida (unidades),Alimentos no numéricos,Carbohidratos (gramos),Carbohidratos (porciones),Insulina de acción lenta no numérica,Insulina de acción lenta (unidades),Notas
        FreeStyle LibreLink,ABC-123,13-09-2026 08:00,0,110,,,,,,,,,
        FreeStyle LibreLink,ABC-123,13-09-2026 08:15,0,125,,,,,,,,,
        FreeStyle LibreLink,ABC-123,13-09-2026 08:20,1,,131,,,,,,,,
        FreeStyle LibreLink,ABC-123,13-09-2026 08:21,6,,,,,,,,,,"comí, después caminé"
        """
    let result = try LibreViewCSV.parse(csv, timeZone: utc)
    #expect(result.readings.map(\.mgdL) == [110, 125, 131])
    #expect(result.readings.first?.date == date("2026-09-13T08:00:00"))
    #expect(result.interval?.end == date("2026-09-13T08:20:00"))
}

@Test func parsesUSExportWithAMPM() throws {
    let csv = """
        Glucose Data,Generated on,10-12-2026 9:00 AM UTC,Generated by,Matias
        Device,Serial Number,Device Timestamp,Record Type,Historic Glucose mg/dL,Scan Glucose mg/dL,Notes
        FreeStyle LibreLink,ABC-123,09-13-2026 01:30 PM,0,98,,
        FreeStyle LibreLink,ABC-123,09-14-2026 01:45 PM,0,102,,"note, with comma"
        """
    let result = try LibreViewCSV.parse(csv, timeZone: utc)
    #expect(result.readings.map(\.date) == [date("2026-09-13T13:30:00"), date("2026-09-14T13:45:00")])
}

@Test func parsesMmolWithSemicolons() throws {
    let csv = """
        Glukosedaten;Erstellt am;12.10.2026 09:00 UTC
        Gerät;Seriennummer;Gerätezeitstempel;Aufzeichnungstyp;Glukosewert-Verlauf mmol/L;Glukose-Scan mmol/L
        FreeStyle LibreLink;ABC-123;13.09.2026 08:00;0;5,5;
        """
    let result = try LibreViewCSV.parse(csv, timeZone: utc)
    #expect(abs(result.readings[0].mgdL - 99.1) < 0.1)
}

@Test func rejectsOtherFiles() {
    #expect(throws: LibreViewCSVError.notLibreView) { try LibreViewCSV.parse("a,b,c\n1,2,3") }
    #expect(throws: LibreViewCSVError.noReadings) {
        try LibreViewCSV.parse("Device,Serial,Time,Type,Historic mg/dL,Scan mg/dL\nX,1,13-09-2026 08:00,6,,")
    }
}

@Test func importKeepsExistingReadings() throws {
    let db = try HistoryDatabase(url: nil)
    let t = date("2026-09-13T08:00:00")
    try db.insert([GlucoseMeasurement(date: t, mgdL: 100, trend: .stable)], patientID: "p")
    let imported = [
        GlucoseMeasurement(date: t, mgdL: 150, trend: nil),
        GlucoseMeasurement(date: t.addingTimeInterval(900), mgdL: 160, trend: nil),
    ]
    #expect(try db.insert(imported, patientID: "p", replacingExisting: false) == 1)
    let stored = try db.readings(patientID: "p", in: DateInterval(start: t, duration: 3600))
    #expect(stored.map(\.mgdL) == [100, 160])
    #expect(stored.first?.trend == .stable)
}
