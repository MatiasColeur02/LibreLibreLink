path = pathlib.Path(__file__).resolve().parent.parent / "Localization/Localizable.xcstrings"
catalog = json.loads(path.read_text())
missing = []
for key, entry in catalog["strings"].items():
    if entry.get("extractionState") == "stale":
        continue
    if key in EN:
        entry.setdefault("localizations", {})["en"] = {"stringUnit": {"state": "translated", "value": EN[key]}}
    elif "en" not in entry.get("localizations", {}):
        missing.append(key)
path.write_text(json.dumps(catalog, ensure_ascii=False, indent=2, sort_keys=True) + "\n")
if missing:
    print("Sin traducción al inglés:", *missing, sep="\n  ")
    sys.exit(1)
print(f"Inglés: {len(catalog['strings'])} claves OK")
